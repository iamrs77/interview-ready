// Builds the "Last-Minute Revision" page of each track: every lesson's "Remember this" box, in sidebar order.
// The page is generated, so it never goes stale. It runs before `npm run dev` and `npm run build`.
// Run by hand: npm run revision
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, relative, resolve, posix } from 'node:path';

const TRACKS = ['system-design', 'low-level-design', 'dsa'];
const PAGE_NAME = 'revision';

// Pages with no lesson of their own to revise.
const SKIPPED_PAGES = ['index', 'cheat-sheet', PAGE_NAME];

const CALLOUT_START = '<Callout title="Remember this" type="success">';
const CALLOUT_END = '</Callout>';

function readMeta(folder) {
  const text = readFileSync(join(folder, 'meta.json'), 'utf8');
  return JSON.parse(text);
}

/** A sidebar entry that is a page or folder name (not a link, separator, "..." or hidden "!page"). */
function isPageEntry(entry) {
  if (typeof entry !== 'string' || entry.trim() === '') {
    return false;
  }
  if (/^(\[|---|!)/.test(entry)) {
    return false;
  }
  return !entry.includes('...');
}

/** The title and the "Remember this" text of one lesson, or null when it has none. */
function readLesson(file) {
  const text = readFileSync(file, 'utf8');

  const titleMatch = text.match(/^title:\s*"?(.+?)"?\s*$/m);
  const title = titleMatch ? titleMatch[1] : file;

  // A planned page is not written yet.
  if (/^planned:\s*true\s*$/m.test(text)) {
    return null;
  }

  const start = text.indexOf(CALLOUT_START);
  if (start === -1) {
    return null;
  }
  const end = text.indexOf(CALLOUT_END, start);
  const body = text.slice(start + CALLOUT_START.length, end);

  return { title, body };
}

/**
 * The callout text, moved from the lesson's folder to the track folder:
 * the 2-space indent is removed, and relative links are fixed so they still point to the same page.
 */
function moveText(body, lessonFile, trackDir) {
  const lines = body.split('\n').map((line) => line.replace(/^ {2}/, ''));
  const text = lines.join('\n').trim();

  return text.replace(/\]\((\.{1,2}\/[^)#]+)(#[^)]*)?\)/g, (match, path, hash) => {
    const target = resolve(dirname(lessonFile), path);
    const fromTrack = relative(trackDir, target).split('\\').join(posix.sep);
    return `](./${fromTrack}${hash ?? ''})`;
  });
}

/** One lesson's part of the page: its title as a link, then its key points. */
function lessonPart(file, trackDir) {
  if (!existsSync(file)) {
    return [];
  }
  const lesson = readLesson(file);
  if (!lesson) {
    return [];
  }

  const link = `./${relative(trackDir, file).split('\\').join(posix.sep)}`;
  const points = moveText(lesson.body, file, trackDir);
  return ['', `**[${lesson.title}](${link})**`, '', points];
}

function buildTrack(track) {
  const trackDir = join(process.cwd(), 'content', track);
  const root = readMeta(trackDir);
  const guideParts = [];
  const folderParts = [];

  for (const entry of root.pages) {
    if (!isPageEntry(entry) || SKIPPED_PAGES.includes(entry)) {
      continue;
    }

    const folder = join(trackDir, entry);
    if (!existsSync(join(folder, 'meta.json'))) {
      // A top-level page, like the Interview Framework.
      guideParts.push(...lessonPart(join(trackDir, `${entry}.mdx`), trackDir));
      continue;
    }

    // A folder of lessons: one heading, then each lesson.
    const meta = readMeta(folder);
    folderParts.push('', `## ${meta.title}`);
    for (const item of meta.pages) {
      if (isPageEntry(item)) {
        folderParts.push(...lessonPart(join(folder, `${item}.mdx`), trackDir));
      }
    }
  }

  const header = [
    '---',
    'title: Last-Minute Revision',
    'description: "Every lesson\'s key points on one page, in order. Read it the night before."',
    'icon: Zap',
    '---',
    '',
    '{/* Generated by scripts/build-revision.mjs from each lesson\'s "Remember this" box. Do not edit by hand. */}',
    '',
    'The **Remember this** box of every lesson, in the same order as the sidebar. Click a title to open the lesson.',
  ];
  const guide = guideParts.length > 0 ? ['', '## Guide', ...guideParts] : [];
  const lines = [...header, ...guide, ...folderParts, ''];

  writeFileSync(join(trackDir, `${PAGE_NAME}.mdx`), lines.join('\n'));
  const lessonCount = [...guideParts, ...folderParts].filter((line) => line.startsWith('**[')).length;
  console.log(`${track}/${PAGE_NAME}.mdx: ${lessonCount} lessons`);
}

for (const track of TRACKS) {
  buildTrack(track);
}
